        response = client.post(url + '/turns/stream', json=dict(text='My idea', language='en', version=0, request_id=str(uuid.uuid4())))
        assert response.status_code == 200, response.text
        assert frames(response)[-1][0] == 'complete'
        assert provider.calls[-1][1]['response_language'] == 'en'
