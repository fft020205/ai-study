class LanguageProvider(TestProvider):
    def __init__(self):
        super().__init__()
        self.hold = None
        self.entered = asyncio.Event()
        self.release = asyncio.Event()

    async def complete_json(self, system, payload):
        if 'exercise' in payload:
            return await super().complete_json(system, payload)
        self.calls.append((system, payload))
        if self.hold == payload['event']:
            self.entered.set()
            await self.release.wait()
        english = payload['response_language'] == 'en'
        return dict(reply='Let us take one small step.' if english else '我们一步一步来。',
                    support_title=('One small step' if english else '慢慢来') if payload['event'] == 'support' else None,
                    focus_id=payload['focus']['id'], move='reflect',
                    exercise_action='keep', exercise=None, assistance='none')

    async def stream_json(self, system, payload):
        result = await self.complete_json(system, payload)
        wire = json.dumps(result, ensure_ascii=False)
        for offset in range(0, len(wire), 7):
            yield wire[offset:offset + 7]
            await asyncio.sleep(0)


def environment(tmp_path, **settings):
    provider = LanguageProvider()
    app = create_app(Settings(database_url=f'sqlite:///{tmp_path}/language.db', _env_file=None, **settings), provider=provider)
    return app, provider


def frames(response):
    return [(block.splitlines()[0][7:], json.loads(block.split('\ndata: ', 1)[1]))
            for block in response.text.split('\n\n') if block.startswith('event: ')]


FLAGS = dict(foreground=True, has_draft=False, composing=False, busy=False, reading=False)


@pytest.mark.parametrize('transport,event', [('turns', 'open'), ('turns', 'message'),
    ('turns/stream', 'open'), ('turns/stream', 'message'), ('turns/stream', 'correct'), ('controls', 'hint'), ('controls', 'correct')])
def test_new_language_reaches_every_generation_path_and_is_persisted(tmp_path, transport, event):
    app, provider = environment(tmp_path)
    with TestClient(app, headers={'X-Study-Client': 'web-v1'}) as client:
        session = client.post('/api/sessions', json={'task_id': 'variable'}).json()
        assert session['language'] == 'zh-CN'
        body = dict(version=session['version'], language='en', text='I am thinking about the example.')
        if transport == 'controls':
            body['action'] = event
        else:
            body.update(event=event, request_id=str(uuid.uuid4()))
        response = client.post(f"/api/sessions/{session['id']}/{transport}", json=body)
        assert response.status_code == 200, response.text
        if transport.endswith('stream'):
            output = frames(response)
            assert output[-1][0] == 'complete', output
            updated = output[-1][1]['session']
            assert ''.join(data['text'] for name, data in output if name == 'delta') == 'Let us take one small step.'
            calls = len(provider.calls)
            replay = client.post(f"/api/sessions/{session['id']}/{transport}", json=body | {'language': 'zh-CN'})
            assert frames(replay)[-1][1]['session']['messages'] == updated['messages']
            assert len(provider.calls) == calls  # A completed request is not regenerated by a language switch.
        else:
            updated = response.json()
        assert updated['language'] == 'en'
        assert updated['messages'][-1]['text'] == 'Let us take one small step.'
        assert all(payload['response_language'] == 'en' for _, payload in provider.calls)
        assert client.get(f"/api/sessions/{session['id']}").json()['language'] == 'en'
        if event == 'hint':
            assert updated['messages'][-2]['text'] == 'Give me a small hint'


def test_legacy_session_defaults_to_chinese_and_omitted_language_keeps_saved_preference(tmp_path):
    app, provider = environment(tmp_path)
    with TestClient(app, headers={'X-Study-Client': 'web-v1'}) as client:
        session = client.post('/api/sessions', json={'task_id': 'mean', 'language': 'en'}).json()
        url = f"/api/sessions/{session['id']}"
        english = client.post(url + '/turns', json=dict(event='open', version=0, request_id=str(uuid.uuid4()))).json()
        assert english['language'] == provider.calls[-1][1]['response_language'] == 'en'
        owner = hashlib.sha256(client.cookies['study_identity'].encode()).hexdigest()
        raw = app.state.repo.get(owner, session['id'])
        raw.pop('language')
        app.state.repo.save(owner, raw, raw['version'])
        legacy = client.get(url).json()
        assert legacy['language'] == 'zh-CN'
        updated = client.post(url + '/turns', json=dict(text='继续', version=legacy['version'], request_id=str(uuid.uuid4()))).json()
        assert updated['language'] == provider.calls[-1][1]['response_language'] == 'zh-CN'
        assert updated['messages'][:len(english['messages'])] == english['messages']


@pytest.mark.parametrize('endpoint', ['create', 'turns', 'turns/stream', 'controls', 'activity'])
def test_unsupported_language_is_rejected_without_calling_model(tmp_path, endpoint):
    app, provider = environment(tmp_path)
    with TestClient(app, headers={'X-Study-Client': 'web-v1'}) as client:
        session = client.post('/api/sessions', json={'task_id': 'variable'}).json()
        payload = dict(language='fr', version=0)
        if endpoint == 'create':
            path = '/api/sessions'
            payload = dict(task_id='variable', language='fr')
        else:
            path = f"/api/sessions/{session['id']}/{endpoint}"
            if endpoint == 'activity': payload.update(FLAGS)
            elif endpoint == 'controls': payload['action'] = 'open'
            else: payload.update(event='open', request_id=str(uuid.uuid4()))
        assert client.post(path, json=payload).status_code == 422
        assert not provider.calls


async def test_heartbeat_language_drives_support_without_changing_camera_or_history(tmp_path):
    app, provider = environment(tmp_path, support_wait_seconds=0)
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://test', headers={'X-Study-Client': 'web-v1'}) as client:
        session = (await client.post('/api/sessions', json={'task_id': 'variable', 'consent': {'support': True}})).json()
        url = f"/api/sessions/{session['id']}"
        session = (await client.post(url + '/turns', json=dict(event='open', version=0, request_id=str(uuid.uuid4())))).json()
        await client.post(url + '/activity', json=FLAGS | dict(version=session['version'], language='en'))
        for _ in range(30):
            await asyncio.sleep(0)
            current = (await client.get(url)).json()
            if not current['pending']: break
        assert current['language'] == 'en'
        assert current['episode']['title'] == 'One small step'
        assert current['episode']['text'] == 'Let us take one small step.'
        assert provider.calls[-1][1]['event'] == 'support'
        assert provider.calls[-1][1]['response_language'] == 'en'
        assert current['messages'] == session['messages']
        assert current['consent'] == session['consent']
        stale = await client.post(url + '/activity', json=FLAGS | dict(version=0, language='zh-CN'))
        assert stale.json()['language'] == 'en'


async def test_switch_during_ordinary_reply_does_not_cancel_stream(tmp_path):
    app, provider = environment(tmp_path)
    provider.hold = 'message'
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://test', headers={'X-Study-Client': 'web-v1'}) as client:
        session = (await client.post('/api/sessions', json={'task_id': 'variable'})).json()
        url = f"/api/sessions/{session['id']}"
        pending = asyncio.create_task(client.post(url + '/turns/stream', json=dict(text='继续', language='zh-CN', version=0, request_id=str(uuid.uuid4()))))
        await asyncio.wait_for(provider.entered.wait(), 2)
        current = (await client.get(url)).json()
        heartbeat = await client.post(url + '/activity', json=FLAGS | dict(version=current['version'], language='en', busy=True))
        assert heartbeat.json()['version'] == current['version']
        assert heartbeat.json()['pending']
        provider.release.set()
        result = await asyncio.wait_for(pending, 2)
        assert frames(result)[-1][0] == 'complete'
        final = (await client.get(url)).json()
        synced = await client.post(url + '/activity', json=FLAGS | dict(version=final['version'], language='en'))
        assert synced.json()['language'] == 'en'
        assert synced.json()['messages'] == final['messages']


async def test_switch_discards_pending_support_in_old_language(tmp_path):
    app, provider = environment(tmp_path, support_wait_seconds=0)
    provider.hold = 'support'
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://test', headers={'X-Study-Client': 'web-v1'}) as client:
        session = (await client.post('/api/sessions', json={'task_id': 'variable', 'consent': {'support': True}})).json()
        url = f"/api/sessions/{session['id']}"
        session = (await client.post(url + '/turns', json=dict(event='open', version=0, request_id=str(uuid.uuid4())))).json()
        await client.post(url + '/activity', json=FLAGS | dict(version=session['version']))
        await asyncio.wait_for(provider.entered.wait(), 2)
        current = (await client.get(url)).json()
        switched = await client.post(url + '/activity', json=FLAGS | dict(version=current['version'], language='en'))
        assert switched.json()['language'] == 'en' and not switched.json()['pending']
        provider.release.set()
        await asyncio.sleep(0)
        final = (await client.get(url)).json()
        assert final['episode'] is None
        assert final['messages'] == session['messages']


def test_automatic_language_sync_does_not_reject_an_already_prepared_message(tmp_path):
    app, provider = environment(tmp_path)
    with TestClient(app, headers={'X-Study-Client': 'web-v1'}) as client:
        session = client.post('/api/sessions', json={'task_id': 'variable'}).json()
